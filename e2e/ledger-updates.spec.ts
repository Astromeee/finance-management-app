test('receivables support partial payment, write-off and recovery in preview', async ({ page, isMobile }) => {
  if (!isMobile) await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/app/goals?vault-preview')
  await page.getByRole('button', { name: 'Add receivable' }).filter({ visible: true }).click()
  await page.getByLabel('Person', { exact: true }).fill('Ali')
  await page.getByLabel('Amount owed', { exact: true }).fill('10000')
  await page.getByRole('button', { name: 'Save receivable', exact: true }).click()
  await page.getByRole('button', { name: /Ali.*10,000/ }).filter({ visible: true }).click()
  await page.getByRole('button', { name: 'Record repayment', exact: true }).click()
  await page.getByLabel('Amount received', { exact: true }).fill('2000')
  await page.getByRole('button', { name: 'Record received', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('2,000 repaid')
  await page.getByRole('button', { name: 'Write off remaining amount', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm write-off', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('8,000 written off')
  await page.getByRole('button', { name: 'Record recovery', exact: true }).click()
  await page.getByLabel('Amount received', { exact: true }).fill('1000')
  await page.getByRole('button', { name: 'Record received', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('7,000 written off')
})

