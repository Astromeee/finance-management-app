test('delete toast has an icon-only Undo that restores the entry', async ({ page, isMobile }) => {
  test.skip(!isMobile)
  await page.goto('/app/transactions?vault-preview')
  const row = page.locator('.mobile-page-content .vault-row').first()
  const title = await row.locator('.vault-row-title').innerText()
  const originalCount = await page.locator('.mobile-page-content .vault-row-title').filter({ hasText: title }).count()
  await row.click()
  await page.getByRole('button', { name: 'Delete', exact: true }).filter({ visible: true }).click()
  const toast = page.getByRole('status').filter({ hasText: 'Transaction deleted' })
  await expect(toast).toBeVisible()
  const undo = toast.getByRole('button', { name: 'Undo', exact: true })
  await expect(undo).toHaveText('')
  await expect(toast).toHaveCSS('opacity', '1')
  await page.screenshot({ path: 'test-results/undo-toast-mobile.png' })
  await undo.click()
  await expect(page.locator('.mobile-page-content .vault-row-title').filter({ hasText: title })).toHaveCount(originalCount)
  await expect(page.getByRole('status')).toContainText('Transaction restored')
})


test('Sunday recap appears once and remains accessible from Story', async ({ page, isMobile }) => {
  test.skip(!isMobile)
  await page.clock.install({ time: new Date('2026-09-13T12:00:00') })
  await page.goto('/app?vault-preview')
  const recap = page.getByRole('dialog', { name: 'Your Sunday recap' })
  await expect(recap).toBeVisible()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: /Good/ }).first()).toBeVisible()
  await page.clock.runFor(1500)
  await expect(recap).toBeHidden()
  await page.getByRole('button', { name: 'Insights', exact: true }).last().click()
  await page.getByRole('button', { name: 'Your latest weekly recap' }).filter({ visible: true }).click()
  await expect(recap).toBeVisible()
})

