import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => { localStorage.setItem('pocket-ledger-pwa-install-prompt-seen', 'true') })
})

test('mobile back closes the add menu and record sheet before returning Home', async ({ page, isMobile }) => {
  test.skip(!isMobile)
  await page.goto('/app?vault-preview')
  await page.getByRole('button', { name: 'Ledger', exact: true }).last().click()
  await expect(page).toHaveURL(/transactions/)
  await page.getByRole('button', { name: 'Add entry', exact: true }).click()
  await expect(page.getByRole('menu')).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('menu')).toBeHidden()
  await expect(page).toHaveURL(/transactions/)
  await page.getByRole('button', { name: 'Add entry', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Record spent' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page).toHaveURL(/transactions/)
  await page.goBack()
  await expect(page).toHaveURL(/\/app\?vault-preview$/)
})

